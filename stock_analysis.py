# Identify crossover points for 20-Day vs 200-Day EMA
prices_ema['Signal'] = prices_ema['20-Day EMA'] > prices_ema['200-Day EMA']

# Crossover occurs when Signal changes
prices_ema['Crossover_Val'] = prices_ema['Signal'].astype(int).diff()

# Filter for actual crossover events
crossovers_only = prices_ema[prices_ema['Crossover_Val'] != 0].dropna(subset=['Crossover_Val']).copy()

# Label the type of cross
crossovers_only['Type'] = crossovers_only['Crossover_Val'].apply(
    lambda x: 'Golden Cross (Bullish)' if x == 1 else 'Death Cross (Bearish)'
)

if not crossovers_only.empty:
    print(f"20/200 EMA Crossover Events for {TICKER_TO_FETCH}:")
    display(crossovers_only[['Close', '20-Day EMA', '200-Day EMA', 'Type']])
else:
    status = 'above' if prices_ema['Signal'].iloc[-1] else 'below'
    print(f"No 20/200 EMA crossovers detected. The 20-day EMA has remained consistently {status} the 200-day EMA.")


# BUY: If you have no shares and a 'Golden Cross' is active,
# it spends all capital to buy shares at the current price.
# SELL: If you own shares and the price closes below the 20-Day EMA,
# it sells everything to lock in gains or limit losses.
def run_strategy_1(df_ema, initial_capital=100000):
    capital = initial_capital
    shares = 0
    trade_log = []

    # Combine data on index
    combined = pd.DataFrame(index=df_ema.index)
    combined['Close'] = df_ema['Close']
    combined['EMA20'] = df_ema['20-Day EMA']
    combined['Golden_Cross'] = df_ema['20-Day EMA'] > df_ema['200-Day EMA']

    for date, row in combined.iterrows():
        price = row['Close']

        # BUY: Golden Cross
        if shares == 0 and row['Golden_Cross']:
            shares = capital / price
            capital = 0
            trade_log.append({'Date': date, 'Action': 'BUY', 'Price': price, 'Strategy': 'Strategy 1'})

        # SELL: Close below EMA 20
        elif shares > 0 and price < row['EMA20']:
            capital = shares * price
            shares = 0
            trade_log.append({'Date': date, 'Action': 'SELL', 'Price': price, 'Strategy': 'Strategy 1'})

    # Force close at end
    if shares > 0:
        capital = shares * combined['Close'].iloc[-1]
        trade_log.append({'Date': combined.index[-1], 'Action': 'FORCE_SELL', 'Price': combined['Close'].iloc[-1], 'Strategy': 'Strategy 1'})

    return capital, pd.DataFrame(trade_log)

# Run Strategy 1
s1_final, s1_trades = run_strategy_1(prices_ema)

