display(s2_trades.tail(5))

# Buy the stock and hold till today
def run_strategy_3(df, initial_capital=100000):
    # Buy and Hold: Buy on the first day, sell on the last day
    start_price = df['Close'].iloc[0]
    end_price = df['Close'].iloc[-1]
    shares = initial_capital / start_price
    final_value = shares * end_price

    trade_log = pd.DataFrame([
        {'Date': df.index[0], 'Action': 'BUY', 'Price': start_price, 'Strategy': 'Strategy 3'},
        {'Date': df.index[-1], 'Action': 'SELL_END', 'Price': end_price, 'Strategy': 'Strategy 3'}
    ])
    return final_value, trade_log


# Buy when Golden Cross happens and Sell when Death Cross happens
def run_strategy_4(df_crossovers, initial_capital=100000):
    # Strategy 4: Golden Cross (Buy) / Death Cross (Sell)
    capital = initial_capital
    shares = 0
    trade_log = []

    for date, row in df_crossovers.iterrows():
        price = row['Close']
        if row['Type'] == 'Golden Cross (Bullish)' and shares == 0:
            shares = capital / price
            capital = 0
            trade_log.append({'Date': date, 'Action': 'BUY', 'Price': price, 'Strategy': 'Strategy 4'})
        elif row['Type'] == 'Death Cross (Bearish)' and shares > 0:
            capital = shares * price
            shares = 0
            trade_log.append({'Date': date, 'Action': 'SELL', 'Price': price, 'Strategy': 'Strategy 4'})

    if shares > 0:
        capital = shares * df_crossovers['Close'].iloc[-1]
        trade_log.append({'Date': df_crossovers.index[-1], 'Action': 'FORCE_SELL', 'Price': df_crossovers['Close'].iloc[-1], 'Strategy': 'Strategy 4'})

    return capital, pd.DataFrame(trade_log)

# Execute strategies
s3_final, s3_trades = run_strategy_3(prices_ema)
s4_final, s4_trades = run_strategy_4(crossovers_only)

# Create new rows for comparison
